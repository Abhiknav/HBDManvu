/**
 * Scans src/assets/story/chapter*\/ and writes the photo list it finds into
 * a generated TypeScript file.
 *
 * This exists so photos can be dropped into a chapter folder under ANY
 * filename — "1.jpeg", "1 (2).jpeg", a raw WhatsApp export, mixed .jpg/.jpeg
 * — without anyone having to rename files or edit a list by hand. Runs
 * automatically before `npm start` and every build.
 */
const fs = require('fs');
const path = require('path');

const STORY_DIR = path.join(__dirname, '..', 'src', 'assets', 'story');
const OUT_FILE = path.join(__dirname, '..', 'src', 'app', 'core', 'story-photos.generated.ts');
const IMAGE_RE = /\.(jpe?g|png|webp|gif|avif)$/i;

/** "2.jpg" sorts before "10.jpg", and "1 (2).jpg" lands next to "1.jpg" */
const naturalSort = (a, b) => a.localeCompare(b, undefined, { numeric: true, sensitivity: 'base' });

function readChapter(dirName) {
  const dir = path.join(STORY_DIR, dirName);
  if (!fs.statSync(dir).isDirectory()) return null;

  const files = fs
    .readdirSync(dir)
    .filter((f) => IMAGE_RE.test(f))
    .sort(naturalSort);

  // spaces and parentheses are legal on disk but must be escaped in a URL
  return files.map((f) => `assets/story/${dirName}/${encodeURIComponent(f)}`);
}

const chapters = fs.existsSync(STORY_DIR)
  ? fs
      .readdirSync(STORY_DIR)
      .filter((name) => /^chapter\d+$/i.test(name))
      .sort(naturalSort)
  : [];

const manifest = {};
for (const name of chapters) {
  const photos = readChapter(name);
  if (photos) manifest[name] = photos;
}

const body = Object.entries(manifest)
  .map(([key, photos]) => {
    if (photos.length === 0) return `  ${key}: [],`;
    const list = photos.map((p) => `    '${p}',`).join('\n');
    return `  ${key}: [\n${list}\n  ],`;
  })
  .join('\n');

const contents = `/**
 * AUTO-GENERATED by scripts/generate-story-manifest.js — do not edit.
 *
 * Reflects whatever image files currently sit in src/assets/story/chapterN/.
 * To change it, add or remove photos in those folders and re-run the build.
 */
export const STORY_PHOTOS: Record<string, string[]> = {
${body}
};
`;

fs.mkdirSync(path.dirname(OUT_FILE), { recursive: true });
fs.writeFileSync(OUT_FILE, contents);

const summary = Object.entries(manifest)
  .map(([k, v]) => `${k}: ${v.length}`)
  .join(', ');
console.log(`generate-story-manifest: ${summary || 'no chapter folders found'}`);
