/**
 * Scans the photo folders under src/assets and writes what it finds into a
 * generated TypeScript file.
 *
 * This exists because photos get dropped in straight from a phone or
 * WhatsApp: mixed extensions (.jpg/.JPG/.JPEG/.PNG/.gif), spaces and
 * parentheses in names, gaps in numbering. Hardcoding paths meant photos
 * silently 404'd and never appeared. Now the filenames on disk are the
 * single source of truth — add photos under any name and they show up.
 *
 * Runs automatically before start, build and deploy.
 */
const fs = require('fs');
const path = require('path');

const ASSETS = path.join(__dirname, '..', 'src', 'assets');
const OUT_FILE = path.join(__dirname, '..', 'src', 'app', 'core', 'photo-manifest.generated.ts');
const IMAGE_RE = /\.(jpe?g|png|webp|gif|avif)$/i;

/** "2.jpg" before "10.jpg", and "1 (2).jpg" next to "1.jpg" */
const naturalSort = (a, b) => a.localeCompare(b, undefined, { numeric: true, sensitivity: 'base' });

/** returns web paths for every image in src/assets/<relDir> */
function scan(relDir) {
  const dir = path.join(ASSETS, relDir);
  if (!fs.existsSync(dir) || !fs.statSync(dir).isDirectory()) return [];

  return fs
    .readdirSync(dir)
    .filter((f) => IMAGE_RE.test(f))
    .sort(naturalSort)
    // spaces and parentheses are legal on disk but must be escaped in a URL
    .map((f) => `assets/${relDir}/${encodeURIComponent(f)}`);
}

const storyChapters = fs.existsSync(path.join(ASSETS, 'story'))
  ? fs
      .readdirSync(path.join(ASSETS, 'story'))
      .filter((name) => /^chapter\d+$/i.test(name))
      .sort(naturalSort)
  : [];

const story = {};
for (const chapter of storyChapters) {
  story[chapter] = scan(path.join('story', chapter).split(path.sep).join('/'));
}

const balloons = scan('balloons');
const wall = scan('wall');
const memories = scan('memories');

const list = (arr, indent = '  ') =>
  arr.length === 0 ? '[]' : `[\n${arr.map((p) => `${indent}  '${p}',`).join('\n')}\n${indent}]`;

const storyBody = Object.entries(story)
  .map(([key, photos]) => `  ${key}: ${list(photos, '  ')},`)
  .join('\n');

const contents = `/**
 * AUTO-GENERATED by scripts/generate-photo-manifest.js — do not edit.
 *
 * Mirrors the image files currently sitting in src/assets. To change any
 * of these lists, add or remove photos in the matching folder and rebuild.
 */
export const STORY_PHOTOS: Record<string, string[]> = {
${storyBody}
};

export const BALLOON_PHOTOS: string[] = ${list(balloons, '')};

export const WALL_PHOTOS: string[] = ${list(wall, '')};

export const MEMORY_PHOTOS: string[] = ${list(memories, '')};
`;

fs.mkdirSync(path.dirname(OUT_FILE), { recursive: true });
fs.writeFileSync(OUT_FILE, contents);

const storySummary = Object.entries(story)
  .map(([k, v]) => `${k}:${v.length}`)
  .join(' ');
console.log(
  `generate-photo-manifest: balloons:${balloons.length} wall:${wall.length} memories:${memories.length} ${storySummary}`
);
